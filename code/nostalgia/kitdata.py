def _acid_cells() -> dict:
    """K03 acid is a two-cell ostinato. Accents follow a 3+3+2 grouping, not every step."""
    cell_a = [42, 42, None, 49, 45, 45, None, 44, 42, None, 52, 49, 47, None, 45, 42]
    cell_b = [54, 52, None, 49, 50, 49, None, 47, 45, None, 49, 45, 44, None, 42, 42]
    accents_a = {0, 3, 10}
    glides_a = {7, 14}
    accents_b = {0, 4, 10}
    glides_b = {12}

    def expand(cell, accents, glides, bars, step_base=0):
        rows = []
        for bar in bars:
            for index, pitch in enumerate(cell):
                if pitch is None:
                    continue
                step = step_base + bar * 16 + index
                velocity = 114 if index in accents else 72
                rows.append((step, 1, pitch, velocity, index in glides))
        return rows

    v01 = expand(cell_a, accents_a, glides_a, [0, 1, 2, 3]) + expand(cell_b, accents_b, glides_b, [4, 5])
    # Last two bars: cell A with the final four steps removed, then a held target.
    trimmed = cell_a[:12] + [None, None, None, None]
    v01 += expand(trimmed, accents_a, glides_a, [6])
    v01 += [(112, 2, 54, 118, False), (116, 1, 49, 80, True), (120, 2, 45, 104, False), (124, 2, 42, 96, False)]
    v02 = expand(cell_b, accents_b, glides_b, [0, 1]) + expand(cell_a, {0, 6, 10}, {4, 14}, [2, 3, 4])
    v02 += expand(cell_b, {0, 8, 12}, {6}, [5, 6])
    v02 += [(112, 1, 42, 110, False), (116, 1, 40, 74, True), (120, 4, 37, 108, False)]
    return {"V01": v01, "V02": v02}


