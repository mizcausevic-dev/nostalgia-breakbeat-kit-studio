"""Original composition data for eight Nostalgia kits.

Patterns are written out, not randomized. Helpers only expand a stated accent
rule (for example closed hats on sixteenths). Each kit has its own kick grid,
snare relationship, bass rhythm, hook, stab rhythm, and acid contour.

Pitch integers use C4 = 60. Ghost velocities stay at or below 55 so later
transforms can find them.
"""

from __future__ import annotations

Hit = tuple  # ("step", step, pitch, velocity, category) or ("tick", tick, ...)


def _hats(length: int, skip: set[int], every: int, strong: int, weak: int, pred=None) -> list[Hit]:
    hits: list[Hit] = []
    for step in range(length):
        if step in skip:
            continue
        if pred is not None and not pred(step):
            continue
        velocity = strong if step % every == 0 else weak
        hits.append(("step", step, 42, velocity, "hat"))
    return hits


def _pairs(pairs: list[tuple[int, int]], pitch: int, category: str) -> list[Hit]:
    return [("step", step, pitch, velocity, category) for step, velocity in pairs]


def _triplet_shaker(bars: int = 4, pitch: int = 82) -> list[Hit]:
    hits: list[Hit] = []
    for bar in range(bars):
        for index, velocity in enumerate((78, 48, 56)):
            tick = bar * 3840 + index * 1280
            hits.append(("tick", tick, pitch, velocity, "shaker"))
    return hits


